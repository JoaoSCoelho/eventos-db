
CREATE TABLE Pessoa 
( 
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR NOT NULL,  
 cpf CHAR(11),  
 passaporte VARCHAR,  
 email VARCHAR NOT NULL,  
 dt_nascimento DATE,  
 pais CHAR(3) NOT NULL,  
 /* associacao_vigente (calculado) BOOLEAN NOT NULL, */ /* REMOVIDO POIS OS CALCULADOS FICARÃO NO SELECT */
 uf CHAR(2) NOT NULL,  
 
 UNIQUE (cpf),
 UNIQUE (passaporte),
 UNIQUE (email)
); 

CREATE TABLE Evento 
( 
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ano INT NOT NULL,  
 dt_inicio DATE NOT NULL,  
 dt_fim DATE NOT NULL,  
 modalidade_edicao VARCHAR NOT NULL,  
 nome_lote_1 VARCHAR NOT NULL,  
 dt_inicio_lote_1 DATE NOT NULL,  
 dt_fim_lote_1 DATE NOT NULL,  
 preco_base_lote_1 NUMERIC(16,2) NOT NULL,  /* 16 dígitos totais, sendo dois depois da vírgula para contar os centavos */
