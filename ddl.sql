 nome_lote_3 VARCHAR,  
 dt_inicio_lote_3 DATE,  
 dt_fim_lote_3 DATE,  
 preco_base_lote_3 NUMERIC(16,2),  
 nome_lote_4 VARCHAR,  
 dt_inicio_lote_4 DATE,  
 dt_fim_lote_4 DATE,  
 preco_base_lote_4 NUMERIC(16,2),  
 sigla VARCHAR NOT NULL,  
 nome VARCHAR NOT NULL,  
 descricao VARCHAR NOT NULL,  
 cidade VARCHAR NOT NULL,  
 estado CHAR(2) NOT NULL,  
 pais CHAR(3) NOT NULL,  
 edicao VARCHAR NOT NULL,  
 tipo VARCHAR NOT NULL,  
 id_agregado_por INT 
); 

CREATE TABLE Categoria_inscricao 
( 
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fator_mult_preco NUMERIC(8,7) NOT NULL DEFAULT 1.0,  /* 8 dígitos, 1 antes e 7 depois da vírgula */
 nome VARCHAR NOT NULL,  
 descricao VARCHAR NOT NULL,  
 id_evento INT NOT NULL
); 

CREATE TABLE Inscricao 
( 
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 /* status (calculado) VARCHAR NOT NULL DEFAULT 'PENDENTE',  
 valor_total (calculado) FLOAT NOT NULL DEFAULT '0',  */
 /* dt_confirmacao (calculado) TIMESTAMP, */ 
 dt_inscricao TIMESTAMP NOT NULL,  /* precisei mudar de DATETIME para TIMESTAMP que é o aceito pelo postgres */ 
 id_categoria INT NOT NULL,  
 id_pessoa INT NOT NULL
); 

CREATE TABLE Atividade 
( 
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
